export function WhatsappFab({ number, message, label }: { number?: string; message: string; label: string }) {
  const href = whatsappLink(number, message);
  if (!href) return null;
  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      aria-label={label}
      className="fixed bottom-5 end-5 z-40 grid size-14 place-items-center rounded-full bg-[#25D366] text-white shadow-lg shadow-black/20 transition hover:scale-105 max-lg:bottom-24"
    >
      <WhatsappIcon className="size-7" />
    </a>
  );
}
